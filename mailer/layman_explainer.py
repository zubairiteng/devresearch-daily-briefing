def extract_layman_terms(text: str, max_terms: int = 3) -> List[Dict[str, str]]:
    """Scan text for technical terms and return simple layman definitions."""
    if not text:
        return []

    text_lower = text.lower()
    matched: List[Dict[str, str]] = []
    seen_terms = set()

    # Search in order of term length (longer terms first to avoid sub-term collisions)
    sorted_terms = sorted(LAYMAN_DICTIONARY.keys(), key=lambda t: len(t), reverse=True)

    for term in sorted_terms:
        # Match as whole word/phrase
        pattern = rf"\b{re.escape(term)}\b"
        if re.search(pattern, text_lower):
            # Check if this term or an alias is already included
            if term not in seen_terms:
                matched.append({
                    "term": term.title(),
                    "explanation": LAYMAN_DICTIONARY[term]
                })
                seen_terms.add(term)
                if len(matched) >= max_terms:
                    break

    return matched


def get_concept_of_the_day(date_obj: Optional[datetime] = None) -> Dict[str, str]:
    """Rotate through featured layman concepts based on the day of year."""
    dt = date_obj or datetime.now()
    index = dt.timetuple().tm_yday % len(FEATURED_CONCEPTS)
    return FEATURED_CONCEPTS[index]
